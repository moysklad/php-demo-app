-- [feature:scenario] журнал срабатываний действий из сценариев, модуль app/scenario
create table scenario_event (
    id bigint generated by default as identity primary key,
    application_id text not null,
    account_id text not null,
    action_name text not null,
    action_type text not null,
    object_type text not null,
    object_id text not null,
    object_name text,
    outcome text not null,
    message text,
    created_at text not null
);

create index ix_scenario_event_application_id on scenario_event (application_id);
create index ix_scenario_event_account_id on scenario_event (account_id);
